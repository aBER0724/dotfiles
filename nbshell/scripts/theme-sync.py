#!/usr/bin/env python3
"""Export the selected nbshell theme for external applications.

Generates palette.sh plus dynamic configs for the terminal (Alacritty), pi,
lazygit, yazi, and herdr (via theme-hook.sh). Run after every theme switch.
"""
from __future__ import annotations

import json
import os
import subprocess
import tempfile
import tomllib
from pathlib import Path

home = Path.home()
config_home = Path(os.environ.get("XDG_CONFIG_HOME", home / ".config"))
config_dir = config_home / "nbshell"
config = json.loads((config_dir / "config.json").read_text())
theme = str(config.get("theme") or "tokyo-night")
colors_path = config_dir / "themes" / theme / "colors.toml"
with colors_path.open("rb") as handle:
    c = tomllib.load(handle)


def get(key: str, fallback: str) -> str:
    return str(c.get(key, fallback))


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".nbshell.", dir=path.parent, text=True)
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


bg = get("background", "#000000")
bg_dark = get("dark_background", bg)
bg_darker = get("darker_background", bg_dark)
bg_light = get("lighter_background", bg)
fg = get("foreground", "#ffffff")
fg_dim = get("dark_foreground", "#808080")
fg_bright = get("bright_foreground", fg)
muted = get("muted", "#808080")
mode = get("mode", "dark")
accent = get("accent", get("blue", "#5f87ff"))
selection = get("selection", bg_light)
red = get("red", "#ff0000")
green = get("green", "#00ff00")
yellow = get("yellow", "#ffff00")
blue = get("blue", accent)
magenta = get("magenta", "#ff00ff")
cyan = get("cyan", "#00ffff")
brown = get("brown", "#808000")

ansi = [
    bg, red, green, yellow, blue, magenta, cyan, fg,
    fg_dim,
    get("bright_red", red), get("bright_green", green), get("bright_yellow", yellow),
    get("bright_blue", blue), get("bright_magenta", magenta), get("bright_cyan", cyan),
    get("bright_foreground", fg),
]
names = [
    "BLACK", "RED", "GREEN", "YELLOW", "BLUE", "MAGENTA", "CYAN", "WHITE",
    "BRIGHT_BLACK", "BRIGHT_RED", "BRIGHT_GREEN", "BRIGHT_YELLOW",
    "BRIGHT_BLUE", "BRIGHT_MAGENTA", "BRIGHT_CYAN", "BRIGHT_WHITE",
]
values = {
    "THEME": theme,
    "MODE": mode,
    "BG": bg,
    "BG_DARK": bg_dark,
    "BG_LIGHT": bg_light,
    "FG": fg,
    "FG_DIM": fg_dim,
    "FG_BRIGHT": fg_bright,
    "ACCENT": accent,
    "ACCENT_ROLE": str(config.get("accent") or "theme"),
    "MUTED": muted,
    "SELECTION": selection,
}
values.update(dict(zip(names, ansi)))

_lines = [
    f"# Generated by nbshell-theme-sync — Theme: {theme}",
    "# Do not edit manually.",
    "",
]
_lines.extend(f"NB_{key}='{value}'" for key, value in values.items())
_lines.extend(["", f'NB_ANSI="{" ".join(ansi)}"', ""])
atomic_write(config_dir / "palette.sh", "\n".join(_lines))

