# Chromium theme extension: Chromium 121+ computes its own UI colors and
# only follows light/dark from GTK/portal, so the css above leaves its
# toolbar grey. A theme extension recolors frame/toolbar/omnibox/NTP from
# the palette; chromium-flags.conf loads it via --load-extension and it is
# applied when the browser starts.
def rgb_triplet(value):
    digits = value.lstrip("#")
    if len(digits) == 3:
        digits = "".join(ch * 2 for ch in digits)
    return [int(digits[i:i + 2], 16) for i in (0, 2, 4)]

