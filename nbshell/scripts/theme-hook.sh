# Publish the light/dark preference through gsettings. The running
# xdg-desktop-portal (gnome backend) forwards color-scheme to Chromium,
# Electron and GTK4; switching gtk-theme makes running GTK apps reload their
# css — including the overrides generated above. Prefer the system glib2
# gsettings: a Homebrew one cannot see the system dconf database.
gsettings_bin=""
if [ -x /usr/bin/gsettings ]; then
  gsettings_bin=/usr/bin/gsettings
elif command -v gsettings >/dev/null 2>&1; then
  gsettings_bin="$(command -v gsettings)"
fi
if [ -n "$gsettings_bin" ] && "$gsettings_bin" list-schemas 2>/dev/null | grep -qx org.gnome.desktop.interface; then
  interface=org.gnome.desktop.interface
  scheme=prefer-dark
  base_theme=Adwaita-dark
  if [ "${NB_MODE:-dark}" = light ]; then
    scheme=prefer-light
    base_theme=Adwaita
  fi
  "$gsettings_bin" set "$interface" color-scheme "$scheme" 2>/dev/null || true
  current="$($gsettings_bin get "$interface" gtk-theme 2>/dev/null | tr -d \')" || current=""
  # Re-setting the same value emits no change notification; hop through the
  # sibling theme so GTK notices and reloads the regenerated palette.
  if [ "$current" = "$base_theme" ]; then
    hop=Adwaita
    [ "$base_theme" = Adwaita ] && hop=Adwaita-dark
    "$gsettings_bin" set "$interface" gtk-theme "$hop" 2>/dev/null || true
  fi
  "$gsettings_bin" set "$interface" gtk-theme "$base_theme" 2>/dev/null || true
fi

# Make Chromium load the theme extension above at startup. Omarchy's
# /usr/bin/chromium launcher appends every line of chromium-flags.conf to
# the command line; upstream's shell wrapper reads the same file. Plain
# binaries without that launcher are skipped.
chromium_bin="$(command -v chromium 2>/dev/null || true)"
if [ -n "$chromium_bin" ] && grep -aqs chromium-flags.conf "$chromium_bin"; then
  flags_conf="${XDG_CONFIG_HOME:-$HOME/.config}/chromium-flags.conf"
  theme_flag="--load-extension=$HOME/.config/nbshell/chromium-theme"
  if ! grep -qsxF -e "$theme_flag" "$flags_conf"; then
    mkdir -p "$(dirname "$flags_conf")"
    printf '%s\n' "$theme_flag" >> "$flags_conf"
    echo "nbshell theme-hook: added '$theme_flag' to $flags_conf — restart Chromium to apply"
  fi
fi

# Reload Chromium's managed policy after updating BrowserThemeColor. This
# immediately recolors running browser chrome when policy refresh is supported.
if [ -n "$chromium_bin" ] && [ -w /etc/chromium/policies/managed/color.json ]; then
  "$chromium_bin" --refresh-platform-policy --no-startup-window >/dev/null 2>&1 || true
fi

# Route the chromium desktop entries through the controller so the RUNNING
# browser can be recolored live (it needs --remote-debugging-pipe from exec
# time; see chromium-controller.mjs). Regenerated from the packaged file so
# package updates propagate; a hand-customized override stays untouched.
nb_controller="${XDG_CONFIG_HOME:-$HOME/.config}/nbshell/chromium-controller.mjs"
nb_node="$(command -v node 2>/dev/null || true)"
nb_desktop_src=/usr/share/applications/chromium.desktop
nb_desktop_dst="${XDG_DATA_HOME:-$HOME/.local/share}/applications/chromium.desktop"
if [ -f "$nb_controller" ] && [ -n "$nb_node" ] && [ -f "$nb_desktop_src" ]; then
  if [ ! -f "$nb_desktop_dst" ] || grep -qs chromium-controller.mjs "$nb_desktop_dst"; then
    sed "s|Exec=/usr/bin/chromium|Exec=$nb_node $nb_controller|" "$nb_desktop_src" > "$nb_desktop_dst"
  fi
elif [ -f "$nb_desktop_dst" ] && grep -qs chromium-controller.mjs "$nb_desktop_dst"; then
  # controller or node is gone — remove our override so launches keep working
  rm -f "$nb_desktop_dst"
fi

# Live theme reload for a running controller-backed Chromium. Plainly
# launched instances simply pick the regenerated theme up on next start.
nb_sock="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/nbshell-chromium.sock"
if [ -S "$nb_sock" ]; then
  python3 - "$nb_sock" <<'PYSOCK'
import socket
import sys

try:
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.settimeout(6)
    s.connect(sys.argv[1])
    s.sendall(b"reload")
    reply = s.recv(4096).decode(errors="replace") or "(no reply)"
    print(f"nbshell theme-hook: chromium live theme reload: {reply}")
except OSError as e:
    print(f"nbshell theme-hook: chromium controller unreachable: {e}", file=sys.stderr)
PYSOCK
fi

# Existing Neovim instances watch palette.sh. Newly launched instances load the
# same generated colorscheme from ~/.config/nvim/colors/nbshell.lua.
exit 0
